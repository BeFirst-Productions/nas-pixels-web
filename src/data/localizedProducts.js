/**
 * Return localized product object based on active language.
 */
export function getLocalizedProduct(product, lang) {
  if (!product) return null;
  if (!lang || lang === "en") return product;

  const translation = productTranslations[product.slug]?.[lang];
  const catTrans = categoryTranslations[lang]?.[product.category];

  if (!translation && !catTrans) return product;

  return {
    ...product,
    title: translation?.title || product.title,
    desc: translation?.desc || product.desc,
    shortDescription: translation?.shortDescription || product.shortDescription,
    category: catTrans || translation?.category || product.category,
    specs: {
      ...product.specs,
      Service: translation?.service || product.specs?.Service,
    },
    details: {
      ...product.details,
      overview: translation?.overview || product.details?.overview,
      keyFeatures: translation?.keyFeatures || product.details?.keyFeatures,
    },
  };
}

/**
 * Return array of localized products.
 */
export function getLocalizedProducts(productsList, lang) {
  if (!Array.isArray(productsList)) return [];
  if (!lang || lang === "en") return productsList;
  return productsList.map((p) => getLocalizedProduct(p, lang));
}

/**
 * Helper to get localized title for TitleBanner by slug
 */
export function getLocalizedProductTitle(slug, lang) {
  if (!slug || !lang || lang === "en") return null;
  return productTranslations[slug]?.[lang]?.title || null;
}
