/**
 * Return localized blog object based on active language.
 * Automatically falls back to English blog properties if missing.
 */
export function getLocalizedBlog(blog, lang) {
  if (!blog) return null;
  if (!lang || lang === "en") return blog;

  const translation = blogTranslations[lang]?.[blog.slug];
  if (!translation) return blog;

  return {
    ...blog,
    title: translation.title || blog.title,
    desc: translation.desc || blog.desc,
    content: translation.content || blog.content,
    tags: translation.tags || blog.tags,
  };
}

/**
 * Return array of localized blog objects.
 */
export function getLocalizedBlogs(blogsList, lang) {
  if (!Array.isArray(blogsList)) return [];
  if (!lang || lang === "en") return blogsList;
  return blogsList.map((b) => getLocalizedBlog(b, lang));
}

/**
 * Helper to get localized title for TitleBanner by slug
 */
export function getLocalizedBlogTitle(slug, lang) {
  if (!slug || !lang || lang === "en") return null;
  return blogTranslations[lang]?.[slug]?.title || null;
}

